"""Plant summary for one unit, from the governed graph (PIDKG_UPGRADE.md, Phase 10).

© 2026 Alan Bowden — Bowden Simulators. All rights reserved.

    reports/summary_<unit>.md

A compact, readable account of what the graph holds: equipment-level flow, instruments and
where they are, loops, SIFs with their initiators and final elements, alarms. It is built
from trusted facts only (trust rule T7, records.TrustedView): a vision fact that is pending
or rejected is left out, and the header says how many were. The header also names the unit
and every source document at its revision, so the summary can be traced.

It is generated by rule, not written by a model: the same graph always gives the same text.

    python -m pid_graph.summary --unit U-100                       (from Neo4j)
    python -m pid_graph.summary --backend memory --pidkg tests/fixtures/pidkg_U-100/graph.json
    python -m pid_graph ...                                        (the pipeline writes it into --out)
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import ontology as O
from .records import TrustedView

ROOT = Path(__file__).resolve().parent.parent
DOC_ORDER = ("PID", "IDX", "CE", "SRS", "LOPA", "CUR")


def _id(key: dict) -> str:
    return str(next(iter(key.values())))


def _table(header: list[str], rows: list[list]) -> list[str]:
    if not rows:
        return []
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return out + ["| " + " | ".join("" if c is None else str(c) for c in r) + " |" for r in rows]


def build(store, unit: str) -> str:
    """The summary as Markdown. store is a MemoryStore or a Neo4jStore; only its trusted view is read."""
    from .reconcile import reconcile
    from .vision_checks import derived_feeds
    view = TrustedView(store)
    hidden = lambda p: p.get("extracted_by") == O.VISION and p.get("review") != "accepted"
    left_out = sum(1 for n in store.nodes() if hidden(n["props"])) + sum(1 for r in store.rels() if hidden(r["props"]))
    nodes = {(n["label"], _id(n["key"])): n["props"] for n in view.nodes() if n["label"] != "Document"}
    rels = view.rels()
    of = lambda typ: [r for r in rels if r["type"] == typ]
    stub = lambda label, ident: " (stub)" if nodes.get((label, ident), {}).get("stub") else ""
    docs = sorted(view.nodes("Document"), key=lambda d: (DOC_ORDER.index(d["props"].get("doc_type")) if d["props"].get("doc_type") in DOC_ORDER else 9, d["key"]["doc_no"]))
    runs = sorted({p.get("load_run") for (lab, _), p in nodes.items() if lab == "Instrument" and p.get("load_run")})

    L = [f"# Plant summary — unit {unit}", "",
         "Built from the governed graph, **trusted facts only** (trust rule T7): facts from the registers, curated entries and pid_audit, "
         "and vision facts an engineer has accepted.",
         f"**{left_out} vision facts are pending or rejected and are left out**; they are in the review register.",
         "This summary is machine-generated by fixed rules from the graph. It is not a design document: check the source documents "
         "below before relying on it.", "",
         f"Load run: {', '.join(runs) or '-'}", "",
         "### Source documents", ""]
    L += ["| Type | Document | Rev | Title |", "|---|---|---|---|"]
    L += [f"| {d['props'].get('doc_type', '')} | {d['key']['doc_no']} | {d['key']['rev']} | {d['props'].get('title', '')}{' (stub)' if d['props'].get('stub') else ''} |" for d in docs]

    # ---- 1. flow ------------------------------------------------------------------------
    L += ["", "## 1. Equipment-level flow", "", "From the pid_audit topology (line level):", ""]
    into: dict[str, set] = {}
    out_of: dict[str, set] = {}
    for r in of("FEEDS"):
        if r["start_label"] == "Equipment" and r["end_label"] == "Line":
            into.setdefault(_id(r["end_key"]), set()).add(_id(r["start_key"]))
        elif r["start_label"] == "Line" and r["end_label"] == "Equipment":
            out_of.setdefault(_id(r["start_key"]), set()).add(_id(r["end_key"]))
    flow_rows = [[a, line, b] for line in sorted(set(into) | set(out_of)) for a in sorted(into.get(line, {"?"})) for b in sorted(out_of.get(line, {"?"}))]
    L += _table(["From", "Line", "To"], flow_rows) or ["None."]
    seg = derived_feeds({"nodes": view.nodes(), "rels": rels})
    L += ["", "From accepted segment-level flow (vision, reviewed):", ""]
    L += _table(["From", "To", "Lines", "Through"], [[f["from"], f["to"], ", ".join(f["via_lines"]), ", ".join(f["via_items"])] for f in seg]) \
        or ["No segment-level flow has been accepted yet."]

    # ---- 2. instruments -------------------------------------------------------------------
    where: dict[str, set] = {}
    for typ in ("MEASURES", "INSTALLED_ON"):
        for r in of(typ):
            where.setdefault(_id(r["start_key"]), set()).add(_id(r["end_key"]))
    pid_docs = {d["key"]["doc_no"] for d in docs if d["props"].get("doc_type") == "PID"}
    shown: dict[str, set] = {}
    for r in of("SHOWN_ON"):
        if r["start_label"] == "Instrument" and r["end_key"].get("doc_no") in pid_docs:
            shown.setdefault(_id(r["start_key"]), set()).add(r["end_key"]["doc_no"])
    inst = sorted((ident, p) for (lab, ident), p in nodes.items() if lab == "Instrument")
    L += ["", "## 2. Instruments and where they are", ""]
    L += _table(["Tag", "Type", "Service", "System", "Location", "Drawings"],
                [[f"{t}{' (stub)' if p.get('stub') else ''}", p.get("type", ""), p.get("service", ""), p.get("system", ""),
                  ", ".join(sorted(where.get(t, set()))), ", ".join(sorted(shown.get(t, set())))] for t, p in inst]) or ["None."]

    # ---- 3. loops ---------------------------------------------------------------------------
    by_loop: dict[str, list] = {}
    for t, p in inst:
        if p.get("loop"):
            by_loop.setdefault(str(p["loop"]), []).append(t)
    L += ["", "## 3. Loops", "", "Per the instrument index (loop number):", ""]
    L += _table(["Loop", "Instruments"], [[k, ", ".join(sorted(v))] for k, v in sorted(by_loop.items())]) or ["None."]
    members: dict[str, list] = {}
    for r in of("MEMBER_OF"):
        members.setdefault(_id(r["end_key"]), []).append(f"{_id(r['start_key'])} ({r['props'].get('role', '')})")
    L += ["", "As drawn (vision, reviewed):", ""]
    L += _table(["Loop", "Type", "Variable", "Members"],
                [[k, p.get("loop_type", ""), p.get("variable", ""), ", ".join(sorted(members.get(k, [])))]
                 for (lab, k), p in sorted(nodes.items()) if lab == "ControlLoop"]) or ["No drawn loop has been accepted yet."]

    # ---- 4. SIFs ------------------------------------------------------------------------------
    L += ["", "## 4. Safety instrumented functions", ""]
    rows = []
    for (lab, sif), p in sorted(nodes.items()):
        if lab != "SIF":
            continue
        ini = sorted((_id(r["start_key"]), r["props"]) for r in of("INITIATES") if _id(r["end_key"]) == sif)
        fin = sorted(f"{_id(r['end_key'])} ({r['props'].get('action', '')})" for r in of("ACTUATES") if _id(r["start_key"]) == sif)
        rows.append([f"{sif}{stub('SIF', sif)}", p.get("sil", ""), p.get("description", ""),
                     ", ".join(f"{t}{stub('Instrument', t)}" for t, _ in ini),
                     ", ".join(sorted({str(x.get("voting")) for _, x in ini if x.get("voting")})),
                     ", ".join(sorted({str(x.get("setpoint")) for _, x in ini if x.get("setpoint")})),
                     ", ".join(fin),
                     ", ".join(sorted(_id(r["end_key"]) for r in of("PROTECTS") if _id(r["start_key"]) == sif)),
                     ", ".join(sorted(_id(r["end_key"]) for r in of("RAISES") if _id(r["start_key"]) == sif)),
                     ", ".join(sorted(f"{_id(r['start_key'])} (rank {r['props'].get('rank', '?')})" for r in of("COMPENSATES_FOR") if _id(r["end_key"]) == sif))])
    L += _table(["SIF", "SIL (C&E)", "Description", "Initiators", "Voting", "Trip setpoint", "Final elements", "Protects", "Announced by",
                 "Curated compensating measures"], rows) or ["None."]

    # ---- 5. alarms -------------------------------------------------------------------------------
    source = {_id(r["end_key"]): _id(r["start_key"]) for r in of("GENERATES")}
    L += ["", "## 5. Alarms", ""]
    L += _table(["Alarm", "Alarm tag", "Source", "Setpoint", "Priority", "Description"],
                [[f"{a}{' (stub)' if p.get('stub') else ''}", p.get("alarm_tag", ""), source.get(a, ""), p.get("setpoint", ""), p.get("priority", ""),
                  p.get("description", "")] for (lab, a), p in sorted(nodes.items()) if lab == "Alarm"]) or ["None."]

    # ---- 6. exceptions -----------------------------------------------------------------------------
    by_code = reconcile(view, unit=unit)["summary"]["exceptions_by_code"]
    L += ["", "## 6. Open exceptions", "",
          "Where the trusted documents disagree or are incomplete, counted from the graph. The exception register lists each one, "
          "and also holds the vision findings (X21 and above), which are not counted here.", ""]
    L += _table(["Code", "Count"], [[c, n] for c, n in sorted(by_code.items(), key=lambda x: int(x[0][1:]))]) or ["None."]
    return "\n".join(L) + "\n"


def write(store, unit: str, out_dir: str | Path) -> Path:
    path = Path(out_dir) / f"summary_{unit}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build(store, unit), encoding="utf-8", newline="\n")
    return path


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--unit", default="U-100")
    ap.add_argument("--backend", choices=["neo4j", "memory"], default="neo4j")
    ap.add_argument("--pidkg", default="", help="memory backend: the pid-to-kg graph.json to load over the U-100 registers")
    ap.add_argument("--out", default=str(ROOT / "reports"))
    a = ap.parse_args(argv)
    if a.backend == "neo4j":
        from .db import DATABASE, get_driver
        from .neo4j_store import Neo4jStore
        d = get_driver()
        try:
            path = write(Neo4jStore(d, DATABASE), a.unit, a.out)
        finally:
            d.close()
    else:
        import json
        from . import load_pidkg as LP
        from . import review as RV
        from .pipeline import build_store
        data = ROOT / "data"
        store, _ = build_store(unit=a.unit, index=data / "U100-INST-INDEX-Rev-B.xlsx", ce=data / "U100-CE-CHART-Rev-A.xlsx",
                               srs=data / "U100-SRS-001-Rev-B.xlsx", lopa=data / "U100-LOPA-001-Rev-A.xlsx",
                               curated=data / "curated" / "compensating_measures_U-100.csv", topology=data / "pid_audit_U100_topology.csv",
                               pdf=data / "U100-PIDS-TX-0057.pdf", transmittal="TX-0057", load_run="memory")
        if a.pidkg:
            register, _ = RV.read_register(ROOT / "reports" / f"review_register_{a.unit}.xlsx")
            LP.apply(store, LP.reconcile(json.loads(Path(a.pidkg).read_text(encoding="utf-8")), LP.index_tags(store), store, unit=a.unit,
                                         load_run="memory", review=RV.decisions(register)))
        path = write(store, a.unit, a.out)
    print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main())

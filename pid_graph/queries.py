"""Fixed, parameterised query templates (decisions section 4).

Only the tag changes. Deterministic retrieval, verified once, reused forever.
Safety-relevant answers come from these templates, never from free-form NLP-to-Cypher.

The unifying frame (decisions section 4): shelved alarm, bypassed SIF initiator, MOS,
interlock bypass are all "this element is out of service - what protection is lost,
what remains, what compensates?"

    python -m pid_graph.queries out_of_service PT-1001A
    python -m pid_graph.queries out_of_service XV-1001
    python -m pid_graph.queries shelve_impact PT-1001A.PAH
    python -m pid_graph.queries moc_impact L-101 --hops 3
    python -m pid_graph.queries trip SIF-100-01
    add --json for machine-readable output
"""
from __future__ import annotations

import argparse
import json
import logging
import re
import sys

from .db import DATABASE, get_driver

# Templates name relationship types (COMPENSATES_FOR, VALID_IN) that are curated later;
# Neo4j warns when a type has no instances yet. Expected until curation starts.
logging.getLogger("neo4j.notifications").setLevel(logging.ERROR)

VOTING_RE = re.compile(r"(\d+)\s*oo\s*(\d+)", re.I)
IMPACT_RELS = "MEASURES|INSTALLED_ON|FEEDS|INITIATES|ACTUATES|PROTECTS|GENERATES"

# ---- Cypher templates ---------------------------------------------------------

Q_AS_INITIATOR = """
MATCH (x:Instrument {tag: $tag})-[i:INITIATES]->(s:SIF)
OPTIONAL MATCH (sib:Instrument)-[si:INITIATES]->(s)
  WHERE sib.tag <> $tag AND coalesce(si.voting, '') = coalesce(i.voting, '')
OPTIONAL MATCH (s)-[:PROTECTS]->(p)
OPTIONAL MATCH (s)-[a:ACTUATES]->(fe:Instrument)
OPTIONAL MATCH (c:Alarm)-[cf:COMPENSATES_FOR]->(s)
OPTIONAL MATCH (c)<-[:GENERATES]-(csrc:Instrument)
WITH s, i, sib, p, fe, a, c, cf, csrc,
     CASE WHEN c IS NULL THEN NULL
          WHEN csrc.tag = $tag THEN 'INVALID NOW: this alarm is generated by the bypassed element itself'
          ELSE 'valid' END AS validity
RETURN s.sif_id AS sif, s.sil AS sil, s.description AS description,
       i.voting AS voting, i.setpoint AS setpoint, i.source_doc AS source,
       collect(DISTINCT sib.tag) AS remaining_initiators,
       collect(DISTINCT coalesce(p.tag, p.line_no)) AS protects,
       collect(DISTINCT fe.tag + ' ' + coalesce(a.action, '')) AS final_elements,
       [x IN collect(DISTINCT {alarm: c.alarm_id, rank: cf.rank, basis: cf.basis, validity: validity,
                                conditions: cf.conditions, curated_by: cf.curated_by, curated_on: cf.curated_on})
        WHERE x.alarm IS NOT NULL | x] AS curated_compensating_alarms
ORDER BY sif
"""

Q_AS_FINAL_ELEMENT = """
MATCH (s:SIF)-[a:ACTUATES]->(x:Instrument {tag: $tag})
OPTIONAL MATCH (s)-[b:ACTUATES]->(o:Instrument) WHERE o.tag <> $tag
OPTIONAL MATCH (s)-[:PROTECTS]->(p)
OPTIONAL MATCH (c:Alarm)-[cf:COMPENSATES_FOR]->(s)
RETURN s.sif_id AS sif, s.sil AS sil, s.description AS description, a.action AS action,
       collect(DISTINCT o.tag + ' ' + coalesce(b.action, '')) AS remaining_final_elements,
       collect(DISTINCT coalesce(p.tag, p.line_no)) AS protects,
       [x IN collect(DISTINCT {alarm: c.alarm_id, rank: cf.rank, basis: cf.basis, validity: 'valid',
                                conditions: cf.conditions, curated_by: cf.curated_by, curated_on: cf.curated_on})
        WHERE x.alarm IS NOT NULL | x] AS curated_compensating_alarms
ORDER BY sif
"""

Q_OWN_ALARMS = """
MATCH (x:Instrument {tag: $tag})-[:GENERATES]->(a:Alarm)
RETURN a.alarm_id AS alarm, a.setpoint AS setpoint, a.priority AS priority
"""

# Heuristic candidates, clearly labelled as such: other devices measuring the same
# variable (same first tag letter) at the place the SIF sensors measure or the SIF
# protects, or within two process hops (FEEDS) of it; SIS devices and the SIF's own
# initiators are excluded (they are not an operations measure). The alarms they
# generate are what operations would watch. COMPENSATES_FOR stays curated-only.
Q_CANDIDATE_COMPENSATION = """
MATCH (x:Instrument {tag: $tag})-[:INITIATES]->(s:SIF)
OPTIONAL MATCH (x)-[:MEASURES]->(loc)
OPTIONAL MATCH (s)-[:PROTECTS]->(p)
WITH x, s, [n IN collect(DISTINCT loc) + collect(DISTINCT p) WHERE n IS NOT NULL] AS places
UNWIND places AS pl
MATCH (pl)-[:FEEDS*0..2]-(near)
WITH DISTINCT x, s, pl, near
MATCH (o:Instrument)-[:MEASURES]->(near)
  WHERE o.tag <> x.tag AND left(o.type, 1) = left(x.type, 1) AND NOT coalesce(o.stub, false)
    AND toUpper(coalesce(o.system, '')) <> 'SIS' AND NOT (o)-[:INITIATES]->(s)
OPTIONAL MATCH (o)-[:GENERATES]->(al:Alarm)
WITH s, o, near,
     collect(DISTINCT CASE WHEN near = pl THEN 'same location as SIF sensor / protected item'
                           ELSE 'within 2 process hops of ' + coalesce(pl.tag, pl.line_no) END) AS relations,
     collect(DISTINCT al.alarm_id + ' @ ' + coalesce(al.setpoint, '?') + ' (' + coalesce(al.priority, '?') + ')') AS alarms
RETURN s.sif_id AS sif, o.tag AS device, o.system AS system, o.role AS role, o.service AS service,
       coalesce(near.tag, near.line_no) AS at, relations, alarms,
       CASE WHEN size(alarms) > 0 THEN 'DCS alarm to operations - recommended'
            WHEN o.role = 'local_indicator' THEN 'field reading only - manual rounds at a defined interval'
            ELSE 'signal without alarm - trend / temporary alarm' END AS how_operations_sees_it
ORDER BY sif, size(alarms) DESC, device
"""

Q_SIBLING_ALARMS = """
MATCH (x:Instrument {tag: $tag})-[:INITIATES]->(s:SIF)<-[:INITIATES]-(sib:Instrument)-[:GENERATES]->(a:Alarm)
WHERE sib.tag <> $tag
RETURN s.sif_id AS sif, sib.tag AS sensor, a.alarm_id AS alarm, a.setpoint AS setpoint,
       'shares its sensor with the SIF: valid only while that sensor itself is in service' AS note
"""

Q_SHELVE = """
MATCH (a:Alarm {alarm_id: $alarm_id})<-[:GENERATES]-(i:Instrument)
OPTIONAL MATCH (i)-[:MEASURES]->(loc)
OPTIONAL MATCH (i)-[:INITIATES]->(s:SIF)
OPTIONAL MATCH (a)-[:COMPENSATES_FOR]->(cs:SIF)
OPTIONAL MATCH (a)-[:VALID_IN]->(st:State)
OPTIONAL MATCH (rs:SIF)-[:RAISES]->(a)
RETURN a.alarm_id AS alarm, a.alarm_tag AS alarm_tag, a.alarm_type AS type, a.setpoint AS setpoint,
       a.priority AS priority, a.description AS description, i.tag AS source, i.type AS variable,
       collect(DISTINCT coalesce(loc.tag, loc.line_no)) AS measures,
       collect(DISTINCT s.sif_id) AS sifs_on_same_sensor,
       collect(DISTINCT cs.sif_id) AS is_compensating_measure_for,
       collect(DISTINCT rs.sif_id) AS announces_trip_of,
       collect(DISTINCT st.state_id) AS valid_in_states
"""

Q_SHELVE_COVER = """
MATCH (a:Alarm {alarm_id: $alarm_id})<-[:GENERATES]-(i:Instrument)-[:MEASURES]->(loc)
MATCH (loc)-[:FEEDS*0..2]-(near)
WITH DISTINCT i, loc, near
MATCH (o:Instrument)-[:MEASURES]->(near)
  WHERE o.tag <> i.tag AND left(o.type, 1) = left(i.type, 1) AND NOT coalesce(o.stub, false)
OPTIONAL MATCH (o)-[:GENERATES]->(oa:Alarm)
OPTIONAL MATCH (o)-[:INITIATES]->(os:SIF)
RETURN coalesce(near.tag, near.line_no) AS at,
       CASE WHEN near = loc THEN 'same location' ELSE 'within 2 process hops' END AS relation,
       o.tag AS other_device, o.system AS system,
       collect(DISTINCT oa.alarm_id + ' @ ' + coalesce(oa.setpoint, '?')) AS other_alarms,
       collect(DISTINCT os.sif_id) AS sifs_still_covering
ORDER BY relation, at, other_device
"""

Q_MOC = """
MATCH (x) WHERE x.tag = $id OR x.line_no = $id OR x.alarm_id = $id OR x.sif_id = $id
MATCH p = (x)-[:%s*..%d]-(a)
WITH x, a, min(length(p)) AS hops
OPTIONAL MATCH (a)-[:SHOWN_ON]->(d:Document)
RETURN labels(a)[0] AS label, coalesce(a.tag, a.line_no, a.alarm_id, a.sif_id) AS id,
       coalesce(a.service, a.description, '') AS description, hops,
       collect(DISTINCT d.doc_no + ' rev ' + d.rev) AS documents
ORDER BY hops, label, id
"""

Q_TRIP = """
MATCH (s:SIF {sif_id: $sif})
OPTIONAL MATCH (i:Instrument)-[ini:INITIATES]->(s)
OPTIONAL MATCH (i)-[:MEASURES]->(loc)
WITH s, i, ini, collect(DISTINCT coalesce(loc.tag, loc.line_no)) AS measures
WITH s, collect(DISTINCT {tag: i.tag, service: i.service, voting: ini.voting, setpoint: ini.setpoint,
                          cause: ini.cause_description, measures: measures, stub: coalesce(i.stub, false)}) AS initiators
OPTIONAL MATCH (s)-[a:ACTUATES]->(fe:Instrument)
WITH s, initiators, collect(DISTINCT {tag: fe.tag, action: a.action, service: fe.service}) AS final_elements
OPTIONAL MATCH (s)-[:PROTECTS]->(p)
WITH s, initiators, final_elements, collect(DISTINCT coalesce(p.tag, p.line_no)) AS protects
OPTIONAL MATCH (s)-[:RAISES]->(ra:Alarm)
WITH s, initiators, final_elements, protects,
     collect(DISTINCT {alarm: ra.alarm_id, alarm_tag: ra.alarm_tag, in_register: NOT coalesce(ra.stub, false)}) AS raises
OPTIONAL MATCH (s)-[:CASCADES_TO]->(cs:SIF)
WITH s, initiators, final_elements, protects, raises, collect(DISTINCT cs.sif_id) AS cascades_to
OPTIONAL MATCH (s)-[:SHOWN_ON]->(d:Document)
RETURN s.sif_id AS sif, s.sil AS sil, s.description AS description, s.logic_solver AS logic_solver,
       initiators, final_elements, protects,
       [x IN raises WHERE x.alarm IS NOT NULL] AS announced_by_alarms, cascades_to,
       collect(DISTINCT d.doc_no + ' rev ' + d.rev) AS documents
"""


# ---- Python wrappers ----------------------------------------------------------

def _run(driver, cypher, **params):
    with driver.session(database=DATABASE) as s:
        return [r.data() for r in s.run(cypher, **params)]


def _needed(voting: str) -> int:
    m = VOTING_RE.search(voting or "")
    return int(m.group(1)) if m else 1


def out_of_service(driver, tag: str) -> dict:
    tag = tag.upper()
    as_init = _run(driver, Q_AS_INITIATOR, tag=tag)
    for r in as_init:
        need = _needed(r["voting"])
        r["initiators_needed"] = need
        r["status"] = "DEGRADED" if len(r["remaining_initiators"]) >= need else "DEFEATED - CANNOT TRIP"
    as_fe = _run(driver, Q_AS_FINAL_ELEMENT, tag=tag)
    for r in as_fe:
        r["status"] = "DEGRADED" if r["remaining_final_elements"] else "DEFEATED - NO FINAL ELEMENT LEFT"
    return {"tag": tag,
            "as_initiator": as_init,
            "as_final_element": as_fe,
            "own_alarms_lost": _run(driver, Q_OWN_ALARMS, tag=tag),
            "sif_sensor_alarms_still_active": _run(driver, Q_SIBLING_ALARMS, tag=tag),
            "candidate_compensation": _run(driver, Q_CANDIDATE_COMPENSATION, tag=tag),
            "note": "curated_compensating_alarms come from COMPENSATES_FOR (engineering judgement only). "
                    "candidate_compensation is a heuristic shortlist for that judgement, not a conclusion."}


def shelve_impact(driver, alarm_id: str) -> dict:
    rows = _run(driver, Q_SHELVE, alarm_id=alarm_id.upper())
    if not rows:
        return {"alarm": alarm_id.upper(), "error": "alarm not in graph"}
    r = rows[0]
    r["cover_at_same_location"] = _run(driver, Q_SHELVE_COVER, alarm_id=alarm_id.upper())
    r["hazard_indication_lost"] = f"{r['type']} on {r['source']} ({r['variable']}) at {', '.join(r['measures']) or '?'}"
    return r


def moc_impact(driver, ident: str, hops: int = 3) -> dict:
    rows = _run(driver, Q_MOC % (IMPACT_RELS, hops), id=ident.upper())
    docs = sorted({d for r in rows for d in r["documents"]})
    by_label: dict[str, list] = {}
    for r in rows:
        by_label.setdefault(r["label"], []).append(r)
    return {"id": ident.upper(), "hops": hops, "affected": len(rows), "by_label": {k: len(v) for k, v in by_label.items()},
            "items": rows, "documents_to_reverify": docs}


def trip(driver, sif: str) -> dict:
    rows = _run(driver, Q_TRIP, sif=sif.upper())
    if not rows:
        return {"sif": sif.upper(), "error": "SIF not in graph"}
    r = rows[0]
    votes = {i["voting"] for i in r["initiators"] if i["voting"]}
    r["voting_check"] = [{"voting": v, "listed": sum(1 for i in r["initiators"] if i["voting"] == v),
                          "expected": int(VOTING_RE.search(v).group(2)) if VOTING_RE.search(v) else None} for v in sorted(votes)]
    return r


# ---- CLI -----------------------------------------------------------------------

def _print(obj, indent=0):
    pad = "  " * indent
    if isinstance(obj, dict):
        for k, v in obj.items():
            if isinstance(v, (dict, list)) and v:
                print(f"{pad}{k}:")
                _print(v, indent + 1)
            else:
                print(f"{pad}{k}: {v if v not in ([], {}, '', None) else '-'}")
    elif isinstance(obj, list):
        for it in obj:
            if isinstance(it, (dict, list)):
                print(f"{pad}-")
                _print(it, indent + 1)
            else:
                print(f"{pad}- {it}")
    else:
        print(f"{pad}{obj}")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("template", choices=["out_of_service", "shelve_impact", "moc_impact", "trip"])
    ap.add_argument("id")
    ap.add_argument("--hops", type=int, default=3)
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    driver = get_driver()
    try:
        fn = {"out_of_service": lambda: out_of_service(driver, a.id), "shelve_impact": lambda: shelve_impact(driver, a.id),
              "moc_impact": lambda: moc_impact(driver, a.id, a.hops), "trip": lambda: trip(driver, a.id)}[a.template]
        res = fn()
    finally:
        driver.close()
    if a.json:
        print(json.dumps(res, indent=2, default=str))
    else:
        _print(res)
    return 0


if __name__ == "__main__":
    sys.exit(main())
